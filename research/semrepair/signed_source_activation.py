"""Practical Ed25519 quorum-authorized source CONFIG activation (not real vendor PKI).

Concrete upgrade from caller-supplied Boolean provenance: issuer-bound
Ed25519 signatures over CANONICAL PATCH MANIFEST plus exact source/replacement
BYTES, deployment contract hash, monotonically incremented version, and
single-use challenge nonce. Two DISTINCT trusted signing roots out of three
must verify; repeated signatures from the same root count only once.

An actual one-file JSON config contains BOTH 2x2 source adapter mappings
and internal control saturation as a unit. After verification, stage and
os.replace() the complete config atomically on the same filesystem, read it
again and check SHA-256, and then read the installed config to execute the
real action adapter before the unchanged official MuJoCo actuator. Tests
reject forged, replayed, source-tampered and partial-signature patches.

SECURITY SCOPE CRITICAL: test signing keys are generated by authors, not
independent robot vendors. This does not authenticate physical tap sensors,
secure the host operating system, defend against root compromise, prove
authorized patches benign, install into a real manufacturer's ROS stack,
or bind a black-box policy to production hardware.
"""
from __future__ import annotations
from dataclasses import dataclass
from hashlib import sha256
from json import dumps,loads
from pathlib import Path
from tempfile import NamedTemporaryFile
from typing import Mapping, Sequence
import os
import re
import math

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

SHA256_RE=re.compile(r"^[0-9a-f]{64}$")
MAX_FILE=8192
PROTOCOL="semrepair-ed25519-2of3-source-config-v1"
MANIFEST_FIELDS=frozenset({
    "protocol","current_source_sha256","replacement_source_sha256",
    "current_epoch","target_epoch","deployment_sha256",
    "expected_nonce","authorized_repair","actor_family",
    "max_abs_input_action",
})
REPAIR_OPTIONS=frozenset(("noop","producer-only","controller-only","atomic"))


def _canonical(value)->bytes:
    return dumps(value,sort_keys=True,separators=(",",":"),allow_nan=False).encode("utf-8")


def _validate_source_config(raw:bytes)->dict:
    if len(raw)>MAX_FILE:
        raise ValueError("source config too large")
    cfg=loads(raw.decode("utf-8"))
    if not isinstance(cfg,dict) or set(cfg)!={"producer","controller","clip"}:
        raise ValueError("source config must contain ONLY producer/controller/clip")
    for name in ("producer","controller"):
        M=cfg[name]
        if not isinstance(M,list) or len(M)!=2 or any(
            not isinstance(row,list) or len(row)!=2 or
            any(type(x) not in (int,float) or not math.isfinite(x) for x in row)
            for row in M):
            raise ValueError("invalid source linear map")
        det=M[0][0]*M[1][1]-M[0][1]*M[1][0]
        if not math.isfinite(det) or abs(det)<1e-10:
            raise ValueError("source maps must be nonsingular")
    if type(cfg["clip"]) not in (int,float) or \
       not math.isfinite(cfg["clip"]) or cfg["clip"]<=0 or cfg["clip"]>1e3:
        raise ValueError("invalid intermediate source control clip")
    if _canonical(cfg)!=raw:
        raise ValueError("source config must use canonical serialized bytes")
    return cfg


def _verify_manifest_shape(m:dict, *, expected_current_epoch:int,
                           expected_nonce:str, expected_actor_family:str,
                           expected_deployment_sha256:str, expected_action_radius:float)->None:
    if not isinstance(m,dict) or set(m)!=MANIFEST_FIELDS:
        raise ValueError("missing or unexpected signed manifest field")
    if m["protocol"]!=PROTOCOL or m["authorized_repair"] not in REPAIR_OPTIONS:
        raise ValueError("unsupported signed protocol or repair class")
    if m["actor_family"]!=expected_actor_family:
        raise ValueError("source-bound deployment robot family differs")
    if m["deployment_sha256"]!=expected_deployment_sha256 or not SHA256_RE.fullmatch(
       str(m["deployment_sha256"])):
        raise ValueError("deployment envelope differs from signed source contract")
    if m["expected_nonce"]!=expected_nonce or not isinstance(expected_nonce,str) or \
       len(expected_nonce)<16:
        raise ValueError("stale or mismatched activation challenge")
    radius=m["max_abs_input_action"]
    if type(radius) not in (int,float) or not math.isfinite(radius) or radius<=0 or \
       not math.isfinite(expected_action_radius) or expected_action_radius<=0 or \
       abs(float(radius)-expected_action_radius)>1e-12:
        raise ValueError("signed deployment action envelope differs from trusted runner")
    if type(m["current_epoch"]) is not int or type(m["target_epoch"]) is not int or \
       m["current_epoch"]!=expected_current_epoch or \
       m["target_epoch"]!=expected_current_epoch+1:
        raise ValueError("rollback or invalid epoch increment")
    for key in ("current_source_sha256","replacement_source_sha256"):
        if not isinstance(m[key],str) or not SHA256_RE.fullmatch(m[key]):
            raise ValueError("invalid source digest")


def _signature_quorum(payload:bytes,signature_records:Sequence[dict],
                      trusted_public_roots:Mapping[str,bytes],threshold:int):
    if threshold<1 or threshold>len(trusted_public_roots):
        raise ValueError("invalid trusted issuer quorum")
    verified=set()
    for record in signature_records:
        if not isinstance(record,dict) or set(record)!={"issuer","ed25519_hex"}:
            raise ValueError("invalid signature record")
        issuer=record["issuer"]
        if not isinstance(issuer,str) or issuer not in trusted_public_roots:
            continue
        if issuer in verified:
            continue
        try:
            pub=Ed25519PublicKey.from_public_bytes(trusted_public_roots[issuer])
            pub.verify(bytes.fromhex(record["ed25519_hex"]),payload)
            verified.add(issuer)
        except (ValueError,TypeError,InvalidSignature):
            continue
    if len(verified)<threshold:
        raise ValueError("insufficient distinct valid Ed25519 source-owner signatures")
    return tuple(sorted(verified))


def verified_atomic_source_activate(
    *, active_config:Path, replacement_bytes:bytes, manifest:dict,
    signatures:Sequence[dict], trusted_public_roots:Mapping[str,bytes],
    expected_current_epoch:int, expected_nonce:str,
    expected_actor_family:str, expected_deployment_sha256:str,
    expected_action_radius:float,
    threshold:int=2,
)->dict:
    """Bound signer approvals to exact OLD+NEW adapter configs and atomically switch.

    Only a regular non-symlink file is permitted. This is a controlled
    demonstration in test filesystem, not end-to-end root-of-trust security.
    """
    active_config=Path(active_config)
    if active_config.is_symlink() or not active_config.is_file():
        raise ValueError("missing original non-symlink adapter source config")
    existing=active_config.read_bytes()
    _validate_source_config(existing)
    _validate_source_config(replacement_bytes)
    _verify_manifest_shape(
        manifest,expected_current_epoch=expected_current_epoch,
        expected_nonce=expected_nonce,expected_actor_family=expected_actor_family,
        expected_deployment_sha256=expected_deployment_sha256,
        expected_action_radius=expected_action_radius)
    if sha256(existing).hexdigest()!=manifest["current_source_sha256"]:
        raise ValueError("original source bytes differ from signed identity")
    if sha256(replacement_bytes).hexdigest()!=manifest["replacement_source_sha256"]:
        raise ValueError("replacement bytes differ from signed patch identity")
    approval=_signature_quorum(
        _canonical(manifest),signatures,trusted_public_roots,threshold)

    # Preserve the correct code-semantic side for an atomic source patch.
    original=_validate_source_config(existing)
    new=_validate_source_config(replacement_bytes)
    for component,repair_token in (("producer","producer-only"),
                                   ("controller","controller-only")):
        authorized=manifest["authorized_repair"] in ("atomic",repair_token)
        if not authorized and new[component]!=original[component]:
            raise ValueError("repair mutates a component outside signed allowed class")
    if new["clip"]!=original["clip"] and manifest["authorized_repair"]!="atomic":
        raise ValueError("internal source limit changed outside atomic signed repair")
    if manifest["authorized_repair"]=="noop" and new!=original:
        raise ValueError("noop repair changes deployed source config")

    # Conditional exact semantic certificate for the complete signed input
    # action box. This does NOT prove any manufacturer's intended task, but
    # prevents even two authorized signers from installing a patch that
    # is known to contradict the declared target identity action contract.
    p=new["producer"]
    c=new["controller"]
    prod=[[sum(c[i][k]*p[k][j] for k in range(2))
           for j in range(2)] for i in range(2)]
    semantic_error=max(abs(prod[i][j]-(1. if i==j else 0.))
                       for i in range(2) for j in range(2))
    max_inner_action=expected_action_radius * max(
        sum(abs(v) for v in row) for row in p)
    if semantic_error>1e-9 or max_inner_action>new["clip"]+1e-9:
        raise ValueError("even signed repair fails full deployment action-envelope certificate")

    # Only after every verification passes do we put any bytes on disk.
    tmpname=None
    try:
        with NamedTemporaryFile(dir=active_config.parent,
                                prefix=".semrepair-stage-",delete=False) as tmp:
            tmpname=tmp.name
            tmp.write(replacement_bytes)
            tmp.flush()
            os.fsync(tmp.fileno())
        # Local attacker with OS root between verification and replacement is
        # excluded; a robust production design needs trusted path descriptors.
        if active_config.is_symlink() or sha256(active_config.read_bytes()).hexdigest()!=\
           manifest["current_source_sha256"]:
            raise ValueError("source changed after signature check and before activation")
        os.replace(tmpname,active_config)
        tmpname=None
        if sha256(active_config.read_bytes()).hexdigest()!=manifest["replacement_source_sha256"]:
            raise RuntimeError("installed source bytes differ from signed replacement")
    finally:
        if tmpname and Path(tmpname).exists():
            Path(tmpname).unlink()
    return {
        "decision":"SIGNED_CONFIG_ACTIVATION_COMPLETED_WITH_ASSUMED_LOCAL_TRUST_ROOTS",
        "source_repair_class":manifest["authorized_repair"],
        "verified_distinct_root_issuers":list(approval),
        "installed_bytes_sha256":manifest["replacement_source_sha256"],
        "activated_epoch":manifest["target_epoch"],
        "source_actor_family":expected_actor_family,
        "semantics_certified_action_radius":expected_action_radius,
        "semantics_max_internal_producer_drive":max_inner_action,
        "cryptographic_primitive":"Ed25519",
        "endorsement_threshold":threshold,
        "does_not_authenticate_telemetry_or_external_robot_manufacturer":True,
    }


def read_executable_control_config(path:Path,expected_source_sha:str)->dict:
    """Actual adapter call-site reload from disk; refuses modified source bytes."""
    path=Path(path)
    if path.is_symlink() or not path.is_file():
        raise ValueError("missing source module")
    source=path.read_bytes()
    if sha256(source).hexdigest()!=expected_source_sha:
        raise ValueError("installed source file modified after activation")
    return _validate_source_config(source)


def execute_loaded_source_action(full_seven_action,installed_config:dict):
    """Use the ACTUAL loaded source maps for joint[0:2]; preserve remaining 5."""
    import numpy as np
    action=np.asarray(full_seven_action,dtype=float)
    if action.shape!=(7,):
        raise ValueError("expected published Pusher seven-torque control")
    P=installed_config["producer"]
    C=installed_config["controller"]
    internal=P@action[:2] if hasattr(P,"__matmul__") else np.array(P)@action[:2]
    intermediate=np.clip(internal,-float(installed_config["clip"]),
                         float(installed_config["clip"]))
    out=np.array(action,dtype=np.float32)
    out[:2]=np.asarray(C)@intermediate
    return out
