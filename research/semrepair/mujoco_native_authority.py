#!/usr/bin/env python3
"""Native MuJoCo semantic-authority experiment synthesis (CPU, no rendering).

Real MuJoCo mechanics instantiate competing semantic worlds; observations are
generated by stepping the actual simulator, not by hand-labeling an observation
table. The separate exact-rational oracle synthesizes a minimum-cost adaptive
probe/tap policy over the measured signatures.

This is a controlled counterfactual, NOT a MuJoCo bug, safety certification,
third-party validation, or maintained external adoption.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from fractions import Fraction
import json
from pathlib import Path
import sys

import mujoco

sys.path.insert(0, str(Path(__file__).resolve().parent))
from independent_oracle import Probe, optimum


@dataclass(frozen=True)
class World:
    name: str
    software_scale: float
    gear: float
    mass: float
    damping: float
    authority: str


WORLDS = (
    World("gain_fault", 1.0, 2.0, 1.0, 0.2, "gear:2-to-1"),
    World("producer_fault", 2.0, 1.0, 1.0, 0.2, "producer:2-to-1"),
    World("reference", 1.0, 1.0, 1.0, 0.2, "noop"),
    World("nuisance_alias", 1.0, 4.0, 2.0, 0.4, "gear:4-to-2"),
)
COMMANDS = (0.0, 0.4, 0.9, -0.3, 0.6, -0.5)
CONTROL_HOLD_STEPS = 15
PRECISION = 8
EFFECT_TOL = 2e-8


def make_model(world: World):
    xml = f"""
    <mujoco model="semantic_abi_{world.name}">
      <option timestep="0.005" gravity="0 0 0" integrator="Euler"/>
      <worldbody>
        <body name="slider">
          <joint name="slide" type="slide" axis="1 0 0" damping="{world.damping}"
                 limited="true" range="-4 4"/>
          <geom name="mass" type="sphere" size="0.05" mass="{world.mass}"/>
        </body>
      </worldbody>
      <actuator>
        <motor name="drive" joint="slide" gear="{world.gear}"
               ctrllimited="true" ctrlrange="-10 10"/>
      </actuator>
    </mujoco>"""
    return mujoco.MjModel.from_xml_string(xml)


def rollout(world: World, commands: tuple[float, ...] = COMMANDS) -> dict:
    model = make_model(world)
    data = mujoco.MjData(model)
    external, software_tap, force_tap = [], [], []
    for command in commands:
        for _ in range(CONTROL_HOLD_STEPS):
            data.ctrl[0] = world.software_scale * command
            mujoco.mj_step(model, data)
            external.append((float(data.qpos[0]), float(data.qvel[0])))
            software_tap.append(float(data.ctrl[0]))
            force_tap.append(float(data.qfrc_actuator[0]))
    return {
        "external": tuple(external),
        "producer_to_controller_ctrl": tuple(software_tap),
        "transmission_force": tuple(force_tap),
        "mujoco": mujoco.__version__,
    }


def signature(values) -> tuple:
    if values and isinstance(values[0], tuple):
        return tuple(tuple(round(x, PRECISION) for x in v) for v in values[::5])
    return tuple(round(v, PRECISION) for v in values[::5])


def max_error(left, right) -> float:
    if len(left) != len(right):
        raise ValueError("different-length trajectories")
    if left and isinstance(left[0], tuple):
        return max(abs(a - b) for l, r in zip(left, right) for a, b in zip(l, r))
    return max(abs(a - b) for a, b in zip(left, right))


def corrected(world: World) -> World:
    if world.name == "gain_fault":
        return replace(world, gear=1.0)
    if world.name == "producer_fault":
        return replace(world, software_scale=1.0)
    if world.name == "nuisance_alias":
        return replace(world, gear=2.0)
    return world


def build_report() -> dict:
    traces = {world.name: rollout(world) for world in WORLDS}
    names = tuple(world.name for world in WORLDS)
    truth = {w.name: w.authority for w in WORLDS}
    ref = traces["reference"]
    gain = traces["gain_fault"]
    producer = traces["producer_fault"]
    nuisance = traces["nuisance_alias"]

    # The external dynamics cannot separate the three different physical
    # worlds: s=1,g=2,m=1; s=2,g=1,m=1; s=1,g=4,m=2,doubled damping.
    external_alias_error = max(
        max_error(gain["external"], producer["external"]),
        max_error(gain["external"], nuisance["external"]),
    )
    assert external_alias_error < EFFECT_TOL, external_alias_error
    assert max_error(gain["external"], ref["external"]) > 1e-4

    # The first internal boundary separates a software-scale fault from the
    # other faults, but leaves the controller-gain/mass nuisance pair aliased.
    assert signature(gain["producer_to_controller_ctrl"]) == signature(
        nuisance["producer_to_controller_ctrl"]
    )
    assert signature(gain["producer_to_controller_ctrl"]) != signature(
        producer["producer_to_controller_ctrl"]
    )

    # A second, deeper tap distinguishes gain=2 from gain=4 even when the
    # external dynamics and pretransmission commands agree exactly.
    assert signature(gain["transmission_force"]) != signature(
        nuisance["transmission_force"]
    )
    assert signature(gain["transmission_force"]) == signature(
        producer["transmission_force"]
    )

    zero = {w.name: rollout(w, (0.0,)) for w in WORLDS}
    assert len({signature(t["external"]) for t in zero.values()}) == 1
    assert len({signature(t["producer_to_controller_ctrl"]) for t in zero.values()}) == 1
    assert len({signature(t["transmission_force"]) for t in zero.values()}) == 1

    probes = (
        Probe(
            "zero-action negative control",
            Fraction(1),
            tuple((w.name, signature(zero[w.name]["external"])) for w in WORLDS),
        ),
        Probe(
            "external state trajectory",
            Fraction(1),
            tuple((w.name, signature(traces[w.name]["external"])) for w in WORLDS),
        ),
        Probe(
            "internal controller input",
            Fraction(2),
            tuple((w.name, signature(traces[w.name]["producer_to_controller_ctrl"])) for w in WORLDS),
            risk=Fraction(1, 4),
        ),
        Probe(
            "internal actuator force",
            Fraction(3),
            tuple((w.name, signature(traces[w.name]["transmission_force"])) for w in WORLDS),
            risk=Fraction(3, 4),
        ),
    )
    optimal = optimum(names, probes, truth)
    external_only = optimum(names, probes[:2], truth)
    without_force = optimum(names, probes[:3], truth)
    risk_blocked = optimum(names, probes, truth, maximum_probe_risk=Fraction(1, 2))

    assert optimal is not None and Fraction(0) < optimal < Fraction(10), optimal
    assert external_only is None
    assert without_force is None
    assert risk_blocked is None

    # Re-execute every concrete local repair in the true physical model.
    # Unlike net transformation equality, repair identities are tied to exact
    # producer and controller implementations; the same output is insufficient
    # to license a repair on the wrong component.
    closure = {}
    for world in WORLDS:
        if world.name == "reference":
            continue
        repaired = rollout(corrected(world))
        err = max_error(repaired["external"], ref["external"])
        assert err < EFFECT_TOL, (world.name, err)
        closure[world.name] = err

    # Negative control: leaving a faulty boundary uncorrected does NOT close
    # the reference effect, even though the multiple faulty worlds alias.
    assert max_error(gain["external"], ref["external"]) > 1e-4

    return {
        "schema": "semrepair-native-mujoco-authority-v1",
        "engine": f"mujoco=={mujoco.__version__}",
        "worlds": [w.name for w in WORLDS],
        "world_authorities": truth,
        "measured_external_alias_max_error": external_alias_error,
        "active_authority_optimum_exact": str(optimal),
        "external_only": "unsafe_unidentifiable" if external_only is None else str(external_only),
        "with_controller_tap_only": "unsafe_unidentifiable" if without_force is None else str(without_force),
        "force_tap_risk_blocked": "unsafe_unidentifiable" if risk_blocked is None else str(risk_blocked),
        "zero_action_all_taps_uninformative": True,
        "concrete_local_repair_effect_closure_max_errors": closure,
        "observation_table_derived_from_mujoco": True,
        "claim_boundary": (
            "Controlled native dynamics with declared world candidates and exact reset; "
            "not discovered upstream defect, arbitrary noise guarantee, learned-policy "
            "task success, or external adoption."
        ),
    }


def main() -> None:
    print(json.dumps(build_report(), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
