#!/usr/bin/env python3
"""P3 independently replayed SOURCE-FITTED model checkpoint on held DreyerB 77-81.

Stage "source" downloads ONLY released source IDs61--68, loads the
earlier author-locked hyperparameter choices from original CI run
38390737635, and serializes reference + all fitted decision states.
Stage "held" runs in a DISTINCT GitHub job, downloads the exact source
checkpoint as a same-run artifact, independently SHA256 verifies the
serialized checkpoint, and evaluates held IDs77--81 WITHOUT any source
re-fitting or new source selection.

joblib/pickle is used only for our own ephemeral GitHub Actions job
artifact generated by immediately preceding job; never load untrusted
network pickle. This experiment remains post-exploratory and within ONE
Dreyer2023B collection, not independent-acquisition validation.
"""
import argparse, hashlib, json, pickle
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score
from moabb.datasets import Dreyer2023B
from moabb.paradigms import MotorImagery
from p3_dreyer2023b_first_source_locked_two_targets import load, SRC
import p3_bnci004_four_operator_same_source as helper

PREVIOUS_RUN=38390737635
PREVIOUS_IDS=[69,70,71,72,73,74,75,76]
HELD=(77,78,79,80,81)
NAMES=("source_macro","continuous","SCE","anisotropic","group_centered")

def dump(path,obj):
    data=(json.dumps(obj,sort_keys=True,indent=2,allow_nan=False)+"\n").encode()
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_bytes(data)
    return hashlib.sha256(data).hexdigest()

def paradigm():
    return MotorImagery(n_classes=2,events=["left_hand","right_hand"],
        channels=["C3","Cz","C4"],fmin=8,fmax=30,resample=160,
        baseline=None,reject_by_annotation=False)

def locked(prior):
    j=json.loads(prior.read_bytes())
    if (j.get("status")!="NEW_TRACKED_DREYER_B_SOURCE_CHOICES_BEFORE_HELD_69_70"
        or j.get("source_public_ids")!=list(SRC)
        or j.get("held_public_ids_NOT_REQUESTED_YET")!=[69,70]):
        raise ValueError("invalid prior original-source lock")
    choices=j["source_policy_choices"]
    if not set(NAMES).issubset(choices):raise ValueError("missing policy choices")
    return j,choices

def stage_source(prior,out):
    frozen,choices=locked(prior)
    c,y,g,receipts,sha=load(Dreyer2023B(),paradigm(),SRC)
    old_receipts=frozen["source_receipts"]
    if len(old_receipts)!=len(receipts):raise RuntimeError("wrong source count")
    for a,b in zip(old_receipts,receipts):
        for key in ("public_id","n","right"):
            if a[key]!=b[key]:raise RuntimeError("source counts/labels drift")
    # All source-derived reference + fitted states are generated before
    # any held ID is requested (this script contains NO held data reads).
    inv=helper.old.reference(c)
    X=helper.old.tangent(c,inv)
    state=helper.old.spectral_state(X,y)
    aniso=helper.fit_aniso(X,y,g)
    group=helper.fit_group_state(X,y,g)
    payload={"reference":inv,"source_scalar_state":state,
             "source_anisotropic_state":aniso,
             "source_group_state":group,"choices":choices}
    out.mkdir(parents=True,exist_ok=True)
    binary=pickle.dumps(payload,protocol=5)
    chk=hashlib.sha256(binary).hexdigest()
    (out/"SOURCE_ONLY_FITTED_FIVE_POLICY_CHECKPOINT.pkl").write_bytes(binary)
    meta={"status":"SOURCE_FITTED_MODELS_PERSISTED_BEFORE_ANY_HELD_READ",
        "prior_run":PREVIOUS_RUN,
        "source_public_ids":list(SRC),"held_public_ids_not_read":list(HELD),
        "source_receipts":receipts,
        "original_source_feature_sha256":frozen["source_preprocessed_covariances_sha256"],
        "new_source_feature_sha256":sha,
        "source_bytes_identical_to_original":sha==frozen["source_preprocessed_covariances_sha256"],
        "prior_hyperparameter_decisions_used_unchanged":True,
        "prior_original_lock_sha256":hashlib.sha256(prior.read_bytes()).hexdigest(),
        "pickle_checkpoint_SHA256":chk,
        "pickle_checkpoint_bytes":len(binary),
        "model_checkpoint_includes_all_five_fitted_source_states":True,
        "source_model_fitting_step_does_not_load_target_subjects":True,
        "warning_pickle_must_not_be_unpickled_from_untrusted_sources":True,
        "task":"motor imagery, within same Dreyer2023B study",
        "no_externally_registered_new_acquisition":True}
    md=dump(out/"P3_FITTED_SOURCE_CHECKPOINT_SHA_LOCK.json",meta)
    print("P3_FITTED_SOURCE_PERSISTED",json.dumps({
        "source_sha":sha,"prior_source_sha":meta["original_source_feature_sha256"],
        "weights_pickle_sha256":chk,"manifest_sha256":md,
        "held_ids_not_read":list(HELD)},sort_keys=True),flush=True)

def score_one(bundle,C,y):
    Z=helper.old.tangent(C,bundle["reference"])
    decisions=bundle["choices"]
    sc={
        "source_macro":helper.old.scalar_scores(
            bundle["source_scalar_state"],Z,decisions["source_macro"]),
        "continuous":helper.old.scalar_scores(
            bundle["source_scalar_state"],Z,decisions["continuous"]),
        "SCE":helper.old.scalar_scores(
            bundle["source_scalar_state"],Z,decisions["SCE"]),
        "anisotropic":helper.score_aniso(
            bundle["source_anisotropic_state"],Z,
            decisions["anisotropic"]["lambda"],decisions["anisotropic"]["alpha"]),
        "group_centered":helper.predict_group(
            bundle["source_group_state"],Z,decisions["group_centered"]["lambda"],"gid")}
    return {k:float(roc_auc_score(y,s)) for k,s in sc.items()}

def stage_held(artifact,out):
    meta=json.loads((artifact/"P3_FITTED_SOURCE_CHECKPOINT_SHA_LOCK.json").read_text())
    if meta.get("status")!="SOURCE_FITTED_MODELS_PERSISTED_BEFORE_ANY_HELD_READ":
        raise RuntimeError("missing prior source-only checkpoint manifest")
    raw=(artifact/"SOURCE_ONLY_FITTED_FIVE_POLICY_CHECKPOINT.pkl").read_bytes()
    if (len(raw)!=meta["pickle_checkpoint_bytes"] or
        hashlib.sha256(raw).hexdigest()!=meta["pickle_checkpoint_SHA256"]):
        raise RuntimeError("checkpoint SHA drift: no held data can be loaded")
    # The file is from our OWN earlier job on this same workflow run.
    bundle=pickle.loads(raw)
    if set(NAMES)!=set(k for k in bundle["choices"] if k in NAMES):
        raise ValueError("frozen policy absent")
    out.mkdir(parents=True,exist_ok=True)
    pre=dump(out/"P3_PERSISTED_CHECKPOINT_VERIFIED_BEFORE_HELD.json",{
        "status":"SAME_RUN_SOURCE_FITTED_CHECKPOINT_VERIFIED",
        "checkpoint_SHA256":meta["pickle_checkpoint_SHA256"],
        "manifest_sha256":hashlib.sha256((artifact/"P3_FITTED_SOURCE_CHECKPOINT_SHA_LOCK.json").read_bytes()).hexdigest(),
        "held_subjects_not_yet_read":list(HELD),
        "no_model_refit_on_held_job":True,
        "source_byte_identity_to_orig":meta["source_bytes_identical_to_original"],
        "old_already_exposed_targets_not_used":PREVIOUS_IDS})
    print("P3_FITTED_CHECKPOINT_TARGET_GATE_SHA",pre,flush=True)
    ds=Dreyer2023B();p=paradigm();rows=[]
    for sid in HELD:
        Ct,yt,_,rec,sha=load(ds,p,[sid])
        auc=score_one(bundle,Ct,yt)
        effects={k:float(v-auc["source_macro"]) for k,v in auc.items()}
        row={"public_id":sid,"n_trials":len(yt),
             "held_feature_SHA256":sha,
             "auc":auc,"paired_delta_AUC":effects}
        rows.append(row)
        print("P3_FITTED_DREYERB_HELD_FIRST_READ",sid,
              json.dumps(row,sort_keys=True),flush=True)
    means={k:float(np.mean([r["paired_delta_AUC"][k] for r in rows]))
           for k in NAMES}
    report={"status":"DREYERB_FIVE_HELD_REUSED_IDENTICAL_FITTED_SOURCE_CHECKPOINT",
        "source_checkpoint_SHA256":meta["pickle_checkpoint_SHA256"],
        "source_only_checkpoint_gate_sha256":pre,
        "source_byte_identity_to_original_run":meta["source_bytes_identical_to_original"],
        "target_ids":list(HELD),"n_newly_read_held_people":len(rows),
        "acquisition_dataset_count":1,
        "real_public_trial_count":sum(r["n_trials"] for r in rows),
        "no_model_refit_or_hyperparameter_reselection_on_held_job":True,
        "no_acquisition_level_significance_or_conformal_claim":True,
        "prior_eight_held_people_known_at_hyperparam_selection_freeze":False,
        "results":rows,"mean_delta_auc_vs_source_macro":means}
    sha=dump(out/"P3_DREYERB_FIVE_HELD_PERSISTED_SOURCE_MODEL_RESULTS.json",report)
    print("P3_FITTED_DREYERB_FIVE_HELD_SUMMARY",
          json.dumps({"means":means,"n":len(rows),"trial_total":report["real_public_trial_count"]},
          sort_keys=True),flush=True)
    print("P3_FITTED_DREYERB_FIVE_HELD_RESULT_SHA",sha,flush=True)

if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--stage",required=True,choices=["source","held"])
    ap.add_argument("--prior-lock",type=Path)
    ap.add_argument("--artifact",type=Path)
    ap.add_argument("--out",type=Path,required=True)
    x=ap.parse_args()
    if x.stage=="source":
        if x.prior_lock is None:ap.error("--prior-lock required")
        stage_source(x.prior_lock,x.out)
    else:
        if x.artifact is None:ap.error("--artifact required")
        stage_held(x.artifact,x.out)
