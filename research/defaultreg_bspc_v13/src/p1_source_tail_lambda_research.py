#!/usr/bin/env python3
"""P1 candidate: choose regularization on worst quartile of strictly source-held-person AUC.
Inputs MUST be generated by an outer-source-person nested evaluator. Not real EEG result.
"""
import numpy as np
def select(rows, lambda_grid, tail=.25, penalty=0.):
    scores=np.asarray(rows,float)
    if scores.ndim!=2 or scores.shape[1]!=len(lambda_grid) or len(scores)<5:raise ValueError('need 5+ independent source rows')
    if not np.isfinite(scores).all() or np.any((scores<0)|(scores>1)) or not(0<tail<=1):raise ValueError('input')
    worst_count=max(1,int(np.ceil(tail*len(scores))))
    lo=np.sort(scores,axis=0)[:worst_count].mean(axis=0)
    stability=scores.std(axis=0,ddof=1)
    j=int(np.argmax(lo-penalty*stability))
    return dict(selected_lambda=float(lambda_grid[j]),mean_source_auc=scores.mean(axis=0).tolist(),
       source_tail_auc=lo.tolist(),stability=stability.tolist(),n_source_people=len(scores),
       caveat='source-only; target improvement is untested, outer source-fold train must exclude test subject')
